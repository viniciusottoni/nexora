using Awaken.Contracts.Exercises;
using Awaken.Domain.Entities.Exercises;

namespace Awaken.Application.Exercises;

public static class ExerciseCatalogMapper
{
    public static ExerciseCatalogResponse ToResponse(this ExerciseCatalog exercise) =>
        new(
            exercise.Id,
            exercise.ProviderName,
            exercise.ProviderExerciseId,
            exercise.NamePtBr,
            exercise.NameOriginal,
            exercise.Slug,
            exercise.DescriptionPtBr,
            exercise.InstructionsPtBr,
            exercise.ExerciseType,
            exercise.MovementPattern,
            exercise.MovementFamily,
            exercise.Mechanic,
            exercise.ForceType,
            exercise.PlaneOfMotion,
            exercise.Laterality,
            exercise.BodyPosition,
            exercise.BenchAngle,
            exercise.EquipmentCategory,
            exercise.LoadType,
            exercise.PrimaryRegion,
            exercise.DifficultyLevel,
            exercise.DifficultyRank,
            exercise.TechnicalComplexity,
            exercise.ImpactLevel,
            exercise.Environment,
            exercise.RequiredEquipment,
            exercise.PrimaryMuscleGroups,
            exercise.SecondaryMuscleGroups,
            exercise.BodyParts,
            exercise.JointStressTags,
            exercise.ContraindicationTags,
            exercise.LimitationBlockTags,
            exercise.PainBlockTags,
            exercise.GoalTags,
            exercise.RiskTags,
            exercise.AccessibilityTags,
            exercise.MinExperienceLevel,
            exercise.SuitableForSedentary,
            exercise.SuitableForBeginner,
            exercise.SuitableForIntermediate,
            exercise.SuitableForAdvanced,
            exercise.IsCompound,
            exercise.IsUnilateral,
            exercise.IsAssisted,
            exercise.IsWeighted,
            exercise.RegressionExerciseIds,
            exercise.ProgressionExerciseIds,
            exercise.RelatedExerciseIds,
            exercise.VideoUrl,
            exercise.ImageUrl,
            exercise.GifUrl,
            exercise.MediaLicenseInfo,
            exercise.SanitizationStatus,
            exercise.IsApprovedForWorkoutGeneration,
            exercise.AttributeContribution is null ? null : new ExerciseAttributeContributionDto(
                exercise.AttributeContribution.PrimaryAttribute,
                exercise.AttributeContribution.StrengthXp,
                exercise.AttributeContribution.AgilityXp,
                exercise.AttributeContribution.EnduranceXp,
                exercise.AttributeContribution.VitalityXp,
                exercise.AttributeContribution.FocusXp,
                exercise.AttributeContribution.WisdomXp,
                exercise.AttributeContribution.IsAutoGenerated),
            exercise.Relations
                .Select(relation => new ExerciseRelationDto(
                    relation.RelatedProviderExerciseId,
                    relation.RelatedName,
                    relation.RelationKind,
                    relation.Types,
                    relation.Score,
                    relation.Confidence,
                    relation.Reasons))
                .ToList());
}
